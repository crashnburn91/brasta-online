create or replace function public.brasta_grant_profile_badge_for_achievement()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.unlocked_at is not null then
    insert into public.player_profile_badges (player_id, badge_key, source, awarded_by, awarded_at)
    select new.player_id, d.badge_key, 'achievement', null, coalesce(new.unlocked_at, now())
    from public.profile_badge_definitions d
    where d.award_type = 'achievement'
      and d.achievement_key = new.achievement_key
    on conflict (player_id, badge_key) do nothing;
  end if;
  return new;
end;
$$;

revoke all on function public.brasta_grant_profile_badge_for_achievement() from public, anon, authenticated;
grant execute on function public.brasta_grant_profile_badge_for_achievement() to service_role;

drop trigger if exists brasta_player_achievement_badge_grant on public.player_achievements;
create trigger brasta_player_achievement_badge_grant
after insert or update of unlocked_at on public.player_achievements
for each row
when (new.unlocked_at is not null)
execute function public.brasta_grant_profile_badge_for_achievement();

insert into public.player_profile_badges (player_id, badge_key, source, awarded_by, awarded_at)
select pa.player_id, d.badge_key, 'achievement', null, pa.unlocked_at
from public.player_achievements pa
join public.profile_badge_definitions d
  on d.award_type = 'achievement'
 and d.achievement_key = pa.achievement_key
where pa.unlocked_at is not null
on conflict (player_id, badge_key) do nothing;

create or replace function public.brasta_equip_profile_badge(p_player_id uuid, p_badge_key text default null)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_badge_key text := nullif(trim(coalesce(p_badge_key, '')), '');
begin
  if not exists (select 1 from public.profiles where id = p_player_id) then
    raise exception 'Player profile not found.';
  end if;

  if v_badge_key is not null and not exists (
    select 1 from public.player_profile_badges
    where player_id = p_player_id and badge_key = v_badge_key
  ) then
    raise exception 'You have not unlocked that badge.';
  end if;

  insert into public.player_profile_badge_equipment (player_id, badge_key, updated_at)
  values (p_player_id, v_badge_key, now())
  on conflict (player_id) do update
    set badge_key = excluded.badge_key,
        updated_at = excluded.updated_at;

  return v_badge_key;
end;
$$;

revoke all on function public.brasta_equip_profile_badge(uuid, text) from public, anon, authenticated;
grant execute on function public.brasta_equip_profile_badge(uuid, text) to service_role;

create or replace function public.brasta_admin_set_profile_badge(
  p_player_id uuid,
  p_badge_key text,
  p_admin_id uuid,
  p_assign boolean
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_badge_key text := trim(coalesce(p_badge_key, ''));
begin
  if not exists (
    select 1 from public.profile_badge_definitions
    where badge_key = v_badge_key and award_type = 'admin'
  ) then
    raise exception 'That badge is not admin assignable.';
  end if;

  if not exists (select 1 from public.profiles where id = p_player_id) then
    raise exception 'Player profile not found.';
  end if;

  if p_assign then
    insert into public.player_profile_badges (player_id, badge_key, source, awarded_by, awarded_at)
    values (p_player_id, v_badge_key, 'admin', p_admin_id, now())
    on conflict (player_id, badge_key) do update
      set source = 'admin', awarded_by = excluded.awarded_by;

    insert into public.profile_badge_admin_log (player_id, badge_key, action, admin_id)
    values (p_player_id, v_badge_key, 'assign', p_admin_id);
  else
    delete from public.player_profile_badges
    where player_id = p_player_id and badge_key = v_badge_key and source = 'admin';

    update public.player_profile_badge_equipment
    set badge_key = null, updated_at = now()
    where player_id = p_player_id and badge_key = v_badge_key;

    insert into public.profile_badge_admin_log (player_id, badge_key, action, admin_id)
    values (p_player_id, v_badge_key, 'revoke', p_admin_id);
  end if;
end;
$$;

revoke all on function public.brasta_admin_set_profile_badge(uuid, text, uuid, boolean) from public, anon, authenticated;
grant execute on function public.brasta_admin_set_profile_badge(uuid, text, uuid, boolean) to service_role;
