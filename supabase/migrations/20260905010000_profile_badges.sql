create table if not exists public.profile_badge_definitions (
  badge_key text primary key,
  name text not null,
  description text not null default '',
  icon text not null default '★',
  category text not null default 'Achievement',
  award_type text not null check (award_type in ('achievement','admin')),
  achievement_key text unique references public.achievement_definitions(achievement_key) on update cascade on delete set null,
  tier text not null default 'standard',
  sort_order integer not null default 0,
  visible boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.player_profile_badges (
  player_id uuid not null references public.profiles(id) on delete cascade,
  badge_key text not null references public.profile_badge_definitions(badge_key) on update cascade on delete cascade,
  source text not null check (source in ('achievement','admin')),
  awarded_by uuid references public.profiles(id) on delete set null,
  awarded_at timestamptz not null default now(),
  primary key (player_id, badge_key)
);

create table if not exists public.player_profile_badge_equipment (
  player_id uuid primary key references public.profiles(id) on delete cascade,
  badge_key text references public.profile_badge_definitions(badge_key) on update cascade on delete set null,
  updated_at timestamptz not null default now()
);

create table if not exists public.profile_badge_admin_log (
  id bigint generated by default as identity primary key,
  player_id uuid not null references public.profiles(id) on delete cascade,
  badge_key text not null references public.profile_badge_definitions(badge_key) on update cascade on delete restrict,
  action text not null check (action in ('assign','revoke')),
  admin_id uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists player_profile_badges_badge_idx on public.player_profile_badges(badge_key, player_id);
create index if not exists profile_badge_admin_log_player_idx on public.profile_badge_admin_log(player_id, created_at desc);

alter table public.profile_badge_definitions enable row level security;
alter table public.player_profile_badges enable row level security;
alter table public.player_profile_badge_equipment enable row level security;
alter table public.profile_badge_admin_log enable row level security;

revoke all on public.profile_badge_definitions from anon, authenticated;
revoke all on public.player_profile_badges from anon, authenticated;
revoke all on public.player_profile_badge_equipment from anon, authenticated;
revoke all on public.profile_badge_admin_log from anon, authenticated;

